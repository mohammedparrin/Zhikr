package com.example.counter

fun dailyHead(m: Boolean): List<Zekr> {
    val a = if (m) "أَصْبَحْنَا" else "أَمْسَيْنَا"
    val b = if (m) "أَصْبَحَ" else "أَمْسَى"
    val c = if (m) "أَصْبَحْتُ" else "أَمْسَيْتُ"
    val day = if (m) "هَذَا الْيَوْمِ" else "هَذِهِ اللَّيْلَةِ"
    val aft = if (m) "بَعْدَهُ" else "بَعْدَهَا"

    val list = mutableListOf<Zekr>()
    list.add(z(KURSI))
    list.add(z(IKHLAS, 3))
    list.add(z(FALAQ, 3))
    list.add(z(NAS, 3))
    list.add(z("${a} وَ${b} الْمُلْكُ لِلَّهِ وَالْحَمْدُ لِلَّهِ، ${TAHLEEL}، رَبِّ أَسْأَلُكَ خَيْرَ مَا فِي ${day} وَخَيْرَ مَا ${aft}، وَأَعُوذُ بِكَ مِنْ شَرِّ مَا فِي ${day} وَشَرِّ مَا ${aft}، رَبِّ أَعُوذُ بِكَ مِنَ الْكَسَلِ وَسُوءِ الْكِبَرِ، رَبِّ أَعُوذُ بِكَ مِنْ عَذَابٍ فِي النَّارِ وَعَذَابٍ فِي الْقَبْرِ"))
    if (m) {
        list.add(z("اللَّهُمَّ بِكَ أَصْبَحْنَا، وَبِكَ أَمْسَيْنَا، وَبِكَ نَحْيَا، وَبِكَ نَمُوتُ وَإِلَيْكَ النُّشُورُ"))
    } else {
        list.add(z("اللَّهُمَّ بِكَ أَمْسَيْنَا، وَبِكَ أَصْبَحْنَا، وَبِكَ نَحْيَا، وَبِكَ نَمُوتُ وَإِلَيْكَ الْمَصِيرُ"))
    }
    list.add(z(SAYYID))
    list.add(z("اللَّهُمَّ إِنِّي ${c} أُشْهِدُكَ، وَأُشْهِدُ حَمَلَةَ عَرْشِكَ، وَمَلَائِكَتَكَ، وَجَمِيعَ خَلْقِكَ، أَنَّكَ أَنْتَ اللَّهُ لَا إِلَٰهَ إِلَّا أَنْتَ وَحْدَكَ لَا شَرِيكَ لَكَ، وَأَنَّ مُحَمَّدًا عَبْدُكَ وَرَسُولُكَ", 4))
    list.add(z("اللَّهُمَّ مَا ${c} بِي مِنْ نِعْمَةٍ أَوْ بِأَحَدٍ مِنْ خَلْقِكَ فَمِنْكَ وَحْدَكَ لَا شَرِيكَ لَكَ، فَلَكَ الْحَمْدُ وَلَكَ الشُّكْرُ"))
    list.add(z("اللَّهُمَّ عَافِنِي فِي بَدَنِي، اللَّهُمَّ عَافِنِي فِي سَمْعِي، اللَّهُمَّ عَافِنِي فِي بَصَرِي، لَا إِلَٰهَ إِلَّا أَنْتَ", 3))
    list.add(z("اللَّهُمَّ إِنِّي أَعُوذُ بِكَ مِنَ الْكُفْرِ وَالْفَقْرِ، وَأَعُوذُ بِكَ مِنْ عَذَابِ الْقَبْرِ، لَا إِلَٰهَ إِلَّا أَنْتَ", 3))
    list.add(z("حَسْبِيَ اللَّهُ لَا إِلَٰهَ إِلَّا هُوَ عَلَيْهِ تَوَكَّلْتُ وَهُوَ رَبُّ الْعَرْشِ الْعَظِيمِ", 7))
    return list
}
